function CalculPrix() {
  //--------------------------------------
  var TPS = 0;
  var TVQ = 0;
  var total = 0;
  var soustotal = 0;
  var Prix = 0;
  var Redevance = 0;
  var gazeline = 0;
  var carburant_site = 0;
  var fraisdistance = 0;
  var fraisdemolition = 0;
  var surplusloc = 0;
  var surpluspoid = 0;
  if ($.isNumeric($("#Prix").val())) {
    Prix = $("#Prix").val();
  }
  else {
    Prix = 0;
  }
  if ($.isNumeric($("#Redevance").val())) {
    Redevance = $("#Redevance").val();
  }
  else {
    Redevance = 0;
  }
  if ($.isNumeric($("#gazeline").val())) {
    gazeline = $("#gazeline").val();
  }
  else {
    gazeline = 0;
  }
  if ($.isNumeric($("#carburant_site").val())) {
    carburant_site = $("#carburant_site").val();
  }
  else {
    carburant_site = 0;
  }
  if ($.isNumeric($("#fraisdistance").val())) {
    fraisdistance = $("#fraisdistance").val();
  }
  else {
    fraisdistance = 0;
  }
  if ($.isNumeric($("#fraisdemolition").val())) {
    fraisdemolition = $("#fraisdemolition").val();
  }
  else {
    fraisdemolition = 0;
  }
  if ($.isNumeric($("#SurplusLocation").val())) {
    surplusloc = $("#SurplusLocation").val();
  }
  else {
    surplusloc = 0;
  }
  if ($.isNumeric($("#SurplusPoids").val())) {
    surpluspoid = $("#SurplusPoids").val();
  }
  else {
    surpluspoid = 0;
  }
  soustotal = (parseFloat(Prix) + parseFloat(Redevance) + parseFloat(gazeline) + parseFloat(surplusloc) + parseFloat(surpluspoid) +
    parseFloat(carburant_site) + parseFloat(fraisdistance) + parseFloat(fraisdemolition));
  TPS = (parseFloat(soustotal) * parseFloat(optTPS)) / 100;
  TVQ = (parseFloat(soustotal) * parseFloat(optTVQ)) / 100;
  $("#TPS").val(TPS.toFixed(2));
  $("#TVQ").val(TVQ.toFixed(2));
  total = (parseFloat(soustotal) + parseFloat($("#TPS").val()) + parseFloat($("#TVQ").val()));
  $("#Total").val(total.toFixed(2));     
}
